import AppKit
import ApplicationServices
import ToolbeltCore

/// Remembers copied text and pastes old copies back.
final class ClipboardController: NSObject {
    private(set) var history: ClipboardHistory
    private let store = JSONStore<ClipboardHistory>(url: Paths.clipboard)
    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var poller: Timer?
    private var saveWork: DispatchWorkItem?
    private var panel: ClipboardPanel?
    /// The app you were in before opening the panel, so the paste lands there.
    private var previousApp: NSRunningApplication?

    /// Copies with any of these types are never read or saved.
    /// Password managers mark secrets with the first ones (see nspasteboard.org).
    private static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        // Universal Clipboard: a copy from your iPhone or iPad. Until an app pastes it, the Mac
        // only holds a placeholder, and reading it right away interferes with the transfer.
        "com.apple.is-remote-clipboard",
    ]

    var isPaused = false

    override init() {
        history = store.load() ?? ClipboardHistory()
        lastChangeCount = pasteboard.changeCount
        super.init()
    }

    func start() {
        // NSPasteboard has no change notification, so check twice a second. It's very cheap.
        let poller = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in self?.checkPasteboard() }
        RunLoop.main.add(poller, forMode: .common)
        self.poller = poller
    }

    private func checkPasteboard() {
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount
        guard !isPaused else { return }
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.skippedTypes),
              let text = pasteboard.string(forType: .string) else { return }
        if history.add(text) { scheduleSave() }
    }

    /// Called after every change to the history.
    private func scheduleSave() {
        NotificationCenter.default.post(name: .clipboardChanged, object: nil)
        saveWork?.cancel()
        let work = DispatchWorkItem { [weak self] in
            guard let self else { return }
            try? self.store.save(self.history)
        }
        saveWork = work
        DispatchQueue.main.asyncAfter(deadline: .now() + 1, execute: work)
    }

    // MARK: Menu

    func addItems(to menu: NSMenu, shortcut: Shortcut?) {
        menu.addInfo("Clipboard")
        menu.addAction("Search history…", target: self, action: #selector(showPanel)).showShortcut(shortcut)
        let recent = NSMenuItem(title: "Recent", action: nil, keyEquivalent: "")
        let submenu = NSMenu()
        if history.items.isEmpty {
            submenu.addInfo("Nothing copied yet")
        }
        for item in history.items.prefix(10) {
            let title = item.preview.count > 50 ? String(item.preview.prefix(50)) + "…" : item.preview
            submenu.addAction(title, target: self, action: #selector(copyFromMenu(_:)), represented: item.id)
        }
        recent.submenu = submenu
        menu.addItem(recent)

        let pause = menu.addAction("Pause saving copies", target: self, action: #selector(togglePause))
        pause.state = isPaused ? .on : .off
        if !AXIsProcessTrusted() {
            menu.addAction("Turn on auto-paste…", target: self, action: #selector(askForAccessibility))
        }
        menu.addAction("Clear history", target: self, action: #selector(clearHistory))
    }

    @objc private func copyFromMenu(_ sender: NSMenuItem) {
        guard let id = sender.representedObject as? UUID,
              let item = history.items.first(where: { $0.id == id }) else { return }
        // The menu doesn't take focus away from the app you're in, so pasting goes straight there.
        previousApp = NSWorkspace.shared.frontmostApplication
        choose(item)
    }

    @objc func togglePause() {
        isPaused.toggle()
        NotificationCenter.default.post(name: .clipboardChanged, object: nil)
    }

    var autoPasteOn: Bool { AXIsProcessTrusted() }

    /// Puts an item back on the clipboard without pasting it.
    func copy(_ item: ClipItem) {
        pasteboard.clearContents()
        pasteboard.setString(item.text, forType: .string)
        lastChangeCount = pasteboard.changeCount
        history.add(item.text)
        scheduleSave()
    }

    func delete(_ item: ClipItem) {
        history.remove(id: item.id)
        scheduleSave()
        panel?.reload(history.items)
    }

    @objc func clearHistory() {
        let alert = NSAlert()
        alert.messageText = "Clear clipboard history?"
        alert.informativeText = "This removes all \(history.items.count) saved copies. It can't be undone."
        alert.addButton(withTitle: "Clear")
        alert.addButton(withTitle: "Cancel")
        NSApp.activate(ignoringOtherApps: true)
        guard alert.runModal() == .alertFirstButtonReturn else { return }
        history.clear()
        scheduleSave()
    }

    @objc func askForAccessibility() {
        let options = [kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String: true] as CFDictionary
        AXIsProcessTrustedWithOptions(options)
    }

    // MARK: Panel

    @objc func showPanel() {
        if let panel, panel.isVisible {
            panel.close()
            return
        }
        previousApp = NSWorkspace.shared.frontmostApplication
        let panel = self.panel ?? ClipboardPanel(onChoose: { [weak self] in self?.choose($0) },
                                                 onDelete: { [weak self] in self?.delete($0) })
        self.panel = panel
        panel.show(history.items)
    }

    /// Puts the item on the clipboard and, with Accessibility allowed, pastes it into the previous app.
    private func choose(_ item: ClipItem) {
        pasteboard.clearContents()
        pasteboard.setString(item.text, forType: .string)
        history.add(item.text)
        scheduleSave()
        panel?.close()

        guard AXIsProcessTrusted(), let app = previousApp,
              app.bundleIdentifier != Bundle.main.bundleIdentifier else { return }
        app.activate()
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.15) {
            Self.pressCommandV()
        }
    }

    private static func pressCommandV() {
        let source = CGEventSource(stateID: .combinedSessionState)
        let vKey: CGKeyCode = 9
        for keyDown in [true, false] {
            let event = CGEvent(keyboardEventSource: source, virtualKey: vKey, keyDown: keyDown)
            event?.flags = .maskCommand
            event?.post(tap: .cghidEventTap)
        }
    }
}
